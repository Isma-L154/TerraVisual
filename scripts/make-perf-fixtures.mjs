/**
 * Generates the reference workspaces the performance budgets are measured
 * against.
 *
 * They are generated rather than hand-written so the three sizes are the same
 * shape, and committed rather than generated at test time so a number measured
 * today is comparable with one measured next year. Regenerating them changes
 * the baseline, which is exactly the sort of thing that should show up in a
 * diff.
 *
 * The shape is deliberately not the easy case. Every subnet references its VPC,
 * every instance references its subnet, and a share of the resources use
 * `count`, so the analyzer does real reference resolution and real expansion
 * rather than parsing a list of independent blocks.
 *
 * Usage: node scripts/make-perf-fixtures.mjs
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SIZES = [50, 200, 1000];
const OUT = join(import.meta.dirname, '..', 'fixtures', 'perf');

/** One VPC per this many resources, so nesting stays realistic as size grows. */
const RESOURCES_PER_VPC = 25;

function workspace(total) {
  const lines = [
    `# Generated by scripts/make-perf-fixtures.mjs — ${total} resources.`,
    '#',
    '# A reference workspace for the performance budgets. Edit the generator,',
    '# not this file.',
    '',
    'provider "aws" {',
    '  region = "eu-west-1"',
    '}',
    '',
    'variable "environment" {',
    '  type    = string',
    '  default = "staging"',
    '}',
    '',
    'locals {',
    '  prefix = "perf-${var.environment}"',
    '}',
    '',
  ];

  let written = 0;
  let vpc = 0;

  while (written < total) {
    lines.push(
      `resource "aws_vpc" "v${vpc}" {`,
      `  cidr_block = "10.${vpc % 250}.0.0/16"`,
      `  name       = "\${local.prefix}-v${vpc}"`,
      '}',
      '',
    );
    written++;

    const inThisVpc = Math.min(RESOURCES_PER_VPC, total - written);

    for (let i = 0; i < inThisVpc; i++) {
      const name = `v${vpc}s${i}`;

      if (i % 5 === 0) {
        // A counted resource, so expansion is exercised rather than skipped.
        lines.push(
          `resource "aws_subnet" "${name}" {`,
          `  count      = 2`,
          `  vpc_id     = aws_vpc.v${vpc}.id`,
          `  cidr_block = cidrsubnet("10.${vpc % 250}.0.0/16", 8, count.index + ${i})`,
          '}',
          '',
        );
      } else if (i % 5 === 1) {
        lines.push(
          `resource "aws_security_group" "${name}" {`,
          `  vpc_id = aws_vpc.v${vpc}.id`,
          `  name   = "\${local.prefix}-${name}"`,
          '}',
          '',
        );
      } else if (i % 5 === 2) {
        lines.push(
          `resource "aws_instance" "${name}" {`,
          `  subnet_id     = aws_subnet.v${vpc}s0[0].id`,
          `  instance_type = "t3.micro"`,
          `  name          = "\${local.prefix}-${name}"`,
          '}',
          '',
        );
      } else if (i % 5 === 3) {
        lines.push(
          `resource "aws_s3_bucket" "${name}" {`,
          `  bucket = lower("\${local.prefix}-${name}")`,
          '}',
          '',
        );
      } else {
        lines.push(
          `resource "aws_lambda_function" "${name}" {`,
          `  function_name = "\${local.prefix}-${name}"`,
          `  role          = "arn:aws:iam::123456789012:role/${name}"`,
          '}',
          '',
        );
      }

      written++;
    }

    vpc++;
  }

  return lines.join('\n');
}

mkdirSync(OUT, { recursive: true });

for (const size of SIZES) {
  const content = workspace(size);
  const path = join(OUT, `${size}.tf`);
  writeFileSync(path, content);
  console.log(`${path}  ${(content.length / 1024).toFixed(1)} kB`);
}
